# Regenerate docs/THIRD_PARTY.md from `cargo metadata` (all features, all targets, normal+build deps;
# dev-dependencies are excluded because they are not shipped). Then, if cargo-deny is installed, run `cargo deny check licenses bans sources`.
# Also regenerates docs/THIRD_PARTY_NOTICES.md (licence texts from the local cargo registry) and checks that every
# source file's SPDX line equals its crate's Cargo `license` (armatura-cli = AGPL-3.0-or-later, others = MPL-2.0).
# Not legal advice. Usage: scripts/licence-audit.sh [--no-deny]
set -euo pipefail
cd "$(dirname "$0")/.."
tmp="$(mktemp)"; trap 'rm -f "$tmp" "$tmp.crates"' EXIT
cargo metadata --format-version 1 --locked --all-features 2>/dev/null >"$tmp"
python3 -I - "$tmp" docs/THIRD_PARTY.md "$tmp.crates" <<'PY'
import json, sys, datetime
meta = json.load(open(sys.argv[1])); out = sys.argv[2]
pk = {p["id"]: p for p in meta["packages"]}
ws = set(meta["workspace_members"])
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
def edges(i):
    for d in nodes[i]["deps"]:
        kinds = {dk["kind"] for dk in d["dep_kinds"]}
        if kinds & {None, "build"}:   # normal or build; dev excluded
            yield d["pkg"]
pulled = {}   # crate id -> set of workspace crate names
for w in sorted(ws):
    seen, st = set(), [w]
    while st:
        x = st.pop()
        for y in edges(x):
            if y not in seen:
                seen.add(y); st.append(y)
    for y in seen:
        if y not in ws: pulled.setdefault(y, set()).add(pk[w]["name"])
PERMISSIVE = {"MIT","Apache-2.0","BSD-2-Clause","BSD-3-Clause","ISC","Zlib","Unlicense","0BSD","BSL-1.0","Apache-2.0 WITH LLVM-exception","CC0-1.0","Unicode-3.0","Unicode-DFS-2016","MIT-0"}
def parse_or(expr):
    return [a.strip().strip("()") for a in expr.replace("/", " OR ").split(" OR ")]
def classify(expr):
    """Return (group, note). group 0 = review (copyleft needed, no permissive alternative), 1 = notable permissive/public-domain variants, 2 = plain permissive."""
    if not expr: return 0, "NO LICENCE FIELD - check manually"
    alts = [[t for t in a.replace("(", " ").replace(")", " ").split(" AND ") ] for a in parse_or(expr)]
    ok = []
    for alt in alts:
        toks = [x.strip() for t in alt for x in t.split() if x not in ("AND","WITH","OR")]
        ok.append(all(t in PERMISSIVE or t in {"LLVM-exception"} for t in toks))
    if not any(ok):
        return 0, "copyleft or unrecognised term; no all-permissive alternative in the expression"
    notable = [t for t in expr.replace("(", " ").replace(")", " ").split() if t in ("CC0-1.0","Unicode-3.0","Unicode-DFS-2016","BSD-2-Clause","BSD-3-Clause","Zlib","ISC","0BSD","Unlicense","BSL-1.0","MIT-0")]
    if " AND " in expr and notable:
        return 1, "also requires " + "/".join(sorted(set(notable))) + " (AND): data-file terms in addition to MIT/Apache"
    if notable and "MIT" not in expr.split() and "Apache-2.0" not in expr.split():
        return 1, "only " + "/".join(sorted(set(notable))) + " terms"
    return 2, ""
rows = []
for i, ps in pulled.items():
    p = pk[i]
    if p["source"] is None: continue
    lic = p.get("license") or ""
    g, note = classify(lic)
    # MPL etc. shown explicitly even if a permissive alt exists
    if any(x in lic for x in ("MPL","GPL","LGPL","EUPL","CDDL","EPL")):
        g = 0 if g == 0 else 1
        note = (note + "; " if note else "") + ("MPL = file-level (weak) copyleft" if "MPL" in lic else "copyleft term") + ("" if g == 0 else " (permissive alternative exists)")
    rows.append((g, p["name"], p["version"], lic or "(none)", p["source"].split("+")[0] + ("" if "crates.io" not in p["source"] else " crates.io"), ", ".join(sorted(ps)), note, p.get("repository") or ""))
rows.sort(key=lambda r: (r[0], r[1].lower(), r[2]))
L = []
L.append("# Third-party licences (generated)\n")
L.append("*Generated by `scripts/licence-audit.sh` from `cargo metadata --all-features` (all targets, normal + build dependencies, dev-dependencies excluded). Do not edit by hand. Not legal advice; the SPDX expressions are what each crate declares in its `Cargo.toml`, they were not independently verified against the source files. The workspace crates themselves are MPL-2.0 (core, capi, wasm, gpu) and AGPL-3.0-or-later (armatura-cli); see LICENSE.*\n")
c = [sum(1 for r in rows if r[0] == g) for g in (0,1,2)]
L.append(f"**{len(rows)} third-party crates** (distinct name+version). Group A (needs review): {c[0]}; group B (notable permissive / public-domain / data licences): {c[1]}; group C (MIT / Apache-2.0 style): {c[2]}.\n")
titles = {0:"A. Needs review: a copyleft term with no all-permissive alternative", 1:"B. Notable permissive, public-domain or data-file licences (no MIT/Apache option offered)", 2:"C. MIT / Apache-2.0 (or a dual including them)"}
for g in (0,1,2):
    sub = [r for r in rows if r[0] == g]
    L.append(f"## {titles[g]}\n")
    if not sub: L.append("*(none)*\n"); continue
    L.append("| Crate | Version | SPDX expression | Source | Pulled in by (workspace) | Note |"); L.append("|---|---|---|---|---|---|")
    for r in sub:
        L.append(f"| {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} |")
    L.append("")
open(out, "w").write("\n".join(L) + "\n")
json.dump([{"name": r[1], "version": r[2], "license": r[3], "repo": r[7], "manifest": pk[i]["manifest_path"]} for r in rows for i in [next(k for k, p in pk.items() if p["name"] == r[1] and p["version"] == r[2])]], open(sys.argv[3], "w"))
print(f"wrote {out}: {len(rows)} crates, groups {c}")
PY

# Regenerate docs/THIRD_PARTY_NOTICES.md: licence texts shipped inside each third-party crate (local cargo registry).
python3 -I - "$tmp.crates" docs/THIRD_PARTY_NOTICES.md <<'PY'
import json, os, sys
crates = sorted(json.load(open(sys.argv[1])), key=lambda c: (c["name"].lower(), c["version"]))
out = ["# Third-party notices (licence texts of bundled dependencies)",
       "Generated by `scripts/licence-audit.sh` from the crate sources in the local cargo registry (do not edit by hand). Required reading before redistributing binaries. These texts belong to their respective authors and keep their own licences; they are not covered by the CC-BY-4.0 that applies to the rest of the documentation. Not legal advice.", ""]
missing = []
for c in crates:
    d = os.path.dirname(c["manifest"]); found = []
    for f in sorted(os.listdir(d)):
        u = f.upper()
        if os.path.isfile(os.path.join(d, f)) and (u.startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE")) or u in ("NOTICE", "NOTICE.md", "NOTICE.txt")):
            found.append(f)
    if not found: missing.append(c); continue
    out += ["---", f"## {c['name']} {c['version']} \u2014 {c['license']}"]
    if c["repo"]: out.append(f"Source: {c['repo']}")
    out.append("")
    for f in found:
        txt = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().rstrip()
        out += [f"### {f}", "```", txt, "```", ""]
if missing:
    out += ["---", "## Crates without a licence file in their package",
            "The published packages of these crates contain no licence text; they are used under the licence named in their `Cargo.toml` (SPDX expression):", ""]
    out += [f"- {c['name']} {c['version']} \u2014 {c['license']}" for c in missing]
    out.append("")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {sys.argv[2]}: {len(crates) - len(missing)} crates with texts, {len(missing)} without")
PY

