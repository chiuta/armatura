# Which builds avoid the MPL-2.0+ crate (smartstring, via rhai, via the `scripting` feature of armatura-core)?
{
echo "## Builds without the MPL-2.0+ crate (smartstring)"
echo
echo "The table above is the union over the whole workspace with all features, where the default CLI enables \`scripting\` and Cargo unifies features. Checked per package with \`cargo tree -i smartstring -e normal,build\`:"
echo
echo "| Build | smartstring in tree? |"; echo "|---|---|"
for spec in "-p armatura-core --no-default-features" "-p armatura-cli --no-default-features" "-p armatura-capi" "-p armatura-wasm" "-p armatura-cli"; do
  if cargo tree $spec -e normal,build -i smartstring >/dev/null 2>&1; then r="yes"; else r="no"; fi
  echo "| \`$spec\` | $r |"
done
} >> docs/THIRD_PARTY.md
# SPDX consistency: every source file must carry its crate's licence (see armatura-cli/tests/spdx_audit.rs).
cargo test --locked -q -p armatura-cli --test spdx_audit
if [ "${1:-}" != "--no-deny" ] && command -v cargo-deny >/dev/null 2>&1; then
  cargo deny --all-features check licenses bans sources
else
  echo "cargo-deny not run (install: cargo install cargo-deny --locked)"
fi
