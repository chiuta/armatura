- **Hash constants** (`noise.rs`): xorshift-multiply finaliser from Chris Wellons' `lowbias32` (public domain, Hash Prospector, 2018); 0x9E3779B1 (2^32 / golden ratio, Knuth); 0x85EBCA6B (MurmurHash3 finaliser, Austin Appleby, public domain).
- **Easing**: `Ease::Bounce` and `Ease::Back` are own derivations (CLEANROOM.md); Robert Penner's BSD-3-Clause constants are no longer used.
- Other algorithms are listed per module with their papers and textbooks in CLEANROOM.md.

